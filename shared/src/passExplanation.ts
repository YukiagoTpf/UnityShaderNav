export type PassSelectionObservation =
  | {
      readonly status: 'observed';
      readonly statement: string;
      readonly materialName: string;
      readonly shaderName: string;
      readonly selectedProgram: MaterialContextProgram;
      readonly citationNodeIds: readonly string[];
    }
  | {
      readonly status: 'not-observed';
      readonly reason:
        | 'material-context-missing'
        | 'material-context-ambiguous'
        | 'selected-program-unavailable';
      readonly statement: string;
      readonly citationNodeIds: readonly string[];
    };

export type PassCausalExplanation =
  | {
      readonly status: 'supported';
      readonly reason: 'authoritative-selection-decision';
      readonly statement: string;
      /** Complete, audit-ready decision fact; never an opaque edge id alone. */
      readonly decision: PassSelectionDecisionEdge;
      readonly citationNodeIds: readonly string[];
    }
  | {
      readonly status: 'refused';
      readonly reason:
        | 'insufficient-evidence'
        | 'contradictory-evidence'
        | 'invalid-evidence';
      readonly statement: string;
      readonly citationNodeIds: readonly string[];
    };

export interface PassExplanationAnswer {
  readonly schemaVersion: typeof PASS_EXPLANATION_SCHEMA_VERSION;
  readonly question: typeof PASS_EXPLANATION_QUESTION;
  readonly graphId: string;
  readonly observation: PassSelectionObservation;
  readonly causalExplanation: PassCausalExplanation;
  readonly disclosures: {
    readonly missing: readonly PassExplanationMissingEvidence[];
    readonly contradictions: readonly PassExplanationContradiction[];
  };
  readonly citations: readonly PassExplanationCitation[];
  /** v1 has no edit protocol or apply authority. */
  readonly suggestedEdits: readonly [];
  readonly execution: {
    readonly authority: 'deterministic-local-evidence-engine';
    readonly locality: 'local-only';
    readonly model: 'not-used';
    readonly telemetry: 'none';
    readonly retention: 'session-only';
  };
}
